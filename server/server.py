"""VerifyFirst optional server (Python standard library only).

Serves the prototype from ../app and adds two endpoints:
  GET  /api/health   -> {"live": true|false}  (true when an API key is configured)
  POST /api/explain  -> {"headline", "summary", "action"} generated by an LLM

The API key is read from the ANTHROPIC_API_KEY environment variable or from a
local .env file in the project root. The key is never sent to the browser and
.env is listed in .gitignore. Without a key the app uses its cached explanations.

Usage:
  python server/server.py            # http://localhost:8000
  python server/server.py --port 8080
"""
from __future__ import annotations

import argparse
import json
import os
import re
import urllib.error
import urllib.request
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_DIR = ROOT / "app"
PROMPT_FILE = ROOT / "prompts" / "explain_prompt.md"
API_URL = os.environ.get("VERIFYFIRST_API_URL", "https://api.anthropic.com/v1/messages")
UNIVERSITY_DOMAIN = "northvale.ac.uk"
PORTAL_HOST = "portal.northvale.ac.uk"
REQUIRED_KEYS = ("headline", "summary", "action")


def load_env(path: Path = ROOT / ".env") -> None:
    """Read KEY=VALUE lines from .env into os.environ (existing values win)."""
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def build_prompt(payload: dict) -> str:
    """Fill the prompt template with the extractor's evidence for one email."""
    evidence = {
        "confidence": payload.get("confidence"),
        "evidence": payload.get("evidence", {}).get("evidence", []),
        "checkable": payload.get("evidence", {}).get("checkable"),
    }
    template = PROMPT_FILE.read_text(encoding="utf-8")
    template = re.sub(r"<!--.*?-->", "", template, flags=re.S).strip()  # notes for developers only
    return (template
            .replace("{UNIVERSITY_DOMAIN}", UNIVERSITY_DOMAIN)
            .replace("{PORTAL_HOST}", PORTAL_HOST)
            .replace("{EVIDENCE_JSON}", json.dumps(evidence, indent=2)))


def parse_explanation(text: str) -> dict:
    """Extract and validate the JSON object returned by the model."""
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        raise ValueError("no JSON object in model output")
    data = json.loads(text[start:end + 1])
    missing = [k for k in REQUIRED_KEYS if not isinstance(data.get(k), str) or not data[k].strip()]
    if missing:
        raise ValueError(f"missing keys: {missing}")
    joined = " ".join(data[k] for k in REQUIRED_KEYS)
    if re.search(r"\b(enter|type|give|provide|send)\s+(in\s+)?(your\s+)?password", joined, re.IGNORECASE):
        # Guard rail: an explanation must never tell the student to enter a password.
        raise ValueError("explanation asks for a password")
    return {k: data[k].strip() for k in REQUIRED_KEYS}


def call_llm(prompt: str, api_key: str, model: str, opener=urllib.request.urlopen) -> dict:
    body = json.dumps({
        "model": model,
        "max_tokens": 300,
        "temperature": 0.2,
        "messages": [{"role": "user", "content": prompt}],
    }).encode("utf-8")
    request = urllib.request.Request(API_URL, data=body, method="POST", headers={
        "content-type": "application/json",
        "x-api-key": api_key,
        "anthropic-version": "2023-06-01",
    })
    with opener(request, timeout=20) as response:
        reply = json.loads(response.read().decode("utf-8"))
    text = "".join(block.get("text", "") for block in reply.get("content", []) if block.get("type") == "text")
    return parse_explanation(text)


class Handler(SimpleHTTPRequestHandler):
    def _json(self, status: int, payload: dict) -> None:
        data = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):  # noqa: N802 (http.server naming)
        if self.path.split("?")[0] == "/api/health":
            return self._json(200, {"live": bool(os.environ.get("ANTHROPIC_API_KEY"))})
        return super().do_GET()

    def do_POST(self):  # noqa: N802
        if self.path != "/api/explain":
            return self._json(404, {"error": "not found"})
        api_key = os.environ.get("ANTHROPIC_API_KEY")
        if not api_key:
            return self._json(503, {"error": "no API key configured"})
        try:
            length = int(self.headers.get("Content-Length", "0"))
            payload = json.loads(self.rfile.read(length) or b"{}")
            prompt = build_prompt(payload)
            model = os.environ.get("VERIFYFIRST_MODEL", "claude-haiku-5-5")
            return self._json(200, call_llm(prompt, api_key, model))
        except (ValueError, KeyError, json.JSONDecodeError) as err:
            return self._json(502, {"error": f"bad model output: {err}"})
        except (urllib.error.URLError, TimeoutError) as err:
            return self._json(502, {"error": f"LLM request failed: {err}"})


def main() -> None:
    parser = argparse.ArgumentParser(description="VerifyFirst prototype server")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()
    load_env()
    handler = partial(Handler, directory=str(APP_DIR))
    server = ThreadingHTTPServer(("127.0.0.1", args.port), handler)
    live = "on" if os.environ.get("ANTHROPIC_API_KEY") else "off (cached explanations only)"
    print(f"VerifyFirst running at http://localhost:{args.port}  |  live explanations: {live}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
